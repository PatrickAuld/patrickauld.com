import { test, expect } from '@playwright/test'
import { clockParts, clockTimestamp, dayBounds, zonedTimestamp } from '../lib/watch-showcase'

test('Pacific clock uses the correct instant and handles daylight saving days', () => {
  const summer = zonedTimestamp('2026-06-21', '12:00', 'America/Los_Angeles')
  expect(new Date(summer).toISOString()).toBe('2026-06-21T19:00:00.000Z')
  expect(clockParts(summer, 'America/Los_Angeles').time).toBe('12:00:00')
  const spring = dayBounds('2026-03-08', 'America/Los_Angeles')
  const fall = dayBounds('2026-11-01', 'America/Los_Angeles')
  expect(spring[1] - spring[0]).toBe(23 * 3600000)
  expect(fall[1] - fall[0]).toBe(25 * 3600000)
  expect(() => zonedTimestamp('2026-03-08', '02:30', 'America/Los_Angeles')).toThrow('does not exist')
  const bounds = dayBounds('2026-06-21', 'America/Los_Angeles')
  const clock = { mode: 'day' as const, timestamp: bounds[0], anchor: 0, speed: 1440, paused: false }
  expect(clockTimestamp(clock, 30000, bounds)).toBe(bounds[0] + 12 * 3600000)
  expect(clockTimestamp(clock, 60000, bounds)).toBe(bounds[0])
  expect(clockTimestamp({ ...clock, paused: true }, 30000, bounds)).toBe(bounds[0])
})

test('Sundial renders different sunlight, scrubs, freezes, and resumes', async ({ page }) => {
  await page.goto('/watches')
  const card = page.locator('[data-showcase="sundial-ii"]')
  await card.scrollIntoViewIfNeeded()
  await expect(card.locator('fieldset')).toBeEnabled({ timeout: 30000 })
  await card.getByRole('button', { name: 'Pause', exact: true }).click()
  await card.getByLabel('Date', { exact: true }).fill('2026-06-21')
  await card.getByLabel('Set time', { exact: true }).fill('12:00:00')
  await expect(card.getByLabel('Displayed time')).toHaveText('12:00:00')
  const noon = await card.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL())
  await card.getByLabel('Set time', { exact: true }).fill('00:00:00')
  await expect(card.getByLabel('Displayed time')).toHaveText('00:00:00')
  await expect.poll(() => card.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL())).not.toBe(noon)
  await card.getByLabel('Scrub through the day', { exact: true }).fill('43200')
  await expect(card.getByLabel('Displayed time')).toHaveText('12:00:00')
  const paused = await card.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL())
  await page.waitForTimeout(350)
  expect(await card.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL())).toBe(paused)
  await card.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(() => card.getByLabel('Displayed time').textContent()).not.toBe('12:00:00')
  await card.getByLabel('Clock mode').selectOption('live')
  await expect(card.getByLabel('Clock mode')).toHaveValue('live')
  await expect(card.getByText('Current time', { exact: true }).first()).toBeVisible()
})

test('theme rotation is labeled, changes the frame, and preserves a fixed clock', async ({ page }) => {
  await page.goto('/watches')
  const card = page.locator('[data-showcase="radial-moire"]')
  await card.scrollIntoViewIfNeeded()
  await expect(card.locator('fieldset')).toBeEnabled({ timeout: 30000 })
  await card.getByLabel('Clock mode').selectOption('fixed')
  await card.getByLabel('Set time', { exact: true }).fill('10:10:00')
  await expect(card.getByLabel('Displayed time')).toHaveText('10:10:00')
  await card.getByLabel('Theme interval').selectOption('4')
  const title = card.locator('[aria-live="polite"]')
  const initialTitle = await title.textContent()
  const initialFrame = await card.getByTestId('watch-stage').getAttribute('style')
  await expect(title).not.toHaveText(initialTitle!, { timeout: 10000 })
  await expect(card.getByTestId('watch-stage')).not.toHaveAttribute('style', initialFrame!)
  await expect(card.getByText(/Theme showcase.*4 seconds/)).toBeVisible()
  await expect(card.getByLabel('Displayed time')).toHaveText('10:10:00')
  await card.getByLabel('Rotate themes').uncheck()
  await card.getByLabel('Theme', { exact: true }).selectOption('0')
  await expect(title).toHaveText(initialTitle!)
  await card.getByLabel('Ambient display').check()
  await expect(card.getByLabel('Ambient display')).toBeChecked()
})

test('showcases fit mobile and reduced motion disables automatic playback', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce', colorScheme: 'dark' })
  const page = await context.newPage()
  await page.goto('/watches')
  const card = page.locator('[data-showcase="sundial-ii"]')
  await card.scrollIntoViewIfNeeded()
  await expect(card.locator('fieldset')).toBeEnabled({ timeout: 30000 })
  await expect(card.getByRole('button', { name: 'Play', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const radial = page.locator('[data-showcase="radial-moire"]')
  await radial.scrollIntoViewIfNeeded()
  await expect(radial.locator('fieldset')).toBeEnabled({ timeout: 30000 })
  await expect(radial.getByLabel('Rotate themes')).not.toBeChecked()
  await context.close()
})
